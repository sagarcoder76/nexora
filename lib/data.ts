export function cityByName(name: string): City | undefined {
  const q = name.trim().toLowerCase();
  return CITIES.find((c) => c.name.toLowerCase() === q) ?? CITIES.find((c) => c.name.toLowerCase().includes(q));
}

export function hotelsByCity(city: string) {
  return HOTELS.filter((h) => h.city.toLowerCase() === city.toLowerCase());
}

export function guidesByCity(city: string) {
  return GUIDES.filter((g) => g.city.toLowerCase() === city.toLowerCase());
}
