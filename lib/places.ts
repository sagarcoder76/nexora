export function groupById(id: string) {
  return PLACE_GROUPS.find((g) => g.id === id);
}

export function placeBySlug(slug: string) {
  return PLACES.find((p) => p.slug === slug);
}

export function placesInGroup(id: string) {
  return PLACES.filter((p) => p.group === id);
}

export function dailyFrom(place: Place) {
  return place.budget.budget;
}

export function tripEstimate(place: Place, tier: "budget" | "mid" | "luxury" = "budget") {
  return place.budget[tier] * place.days;
}
